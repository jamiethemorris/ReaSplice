'use strict';
const assert = require('node:assert/strict');
const create = require('./bridge-volume');
const tick = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  let state, errors = [], calls = [];
  const control = create({ request: payload => new Promise((resolve, reject) => calls.push({ payload, resolve, reject })), onChange: value => { state = value; }, onError: error => errors.push(error) });
  control.updateProject('a');
  let read = control.refresh(); calls.shift().resolve({ projectId: 'a', trackId: 'one', volume: 1 }); await read;
  assert.equal(state.volume, 1);
  control.setVolume(.5); control.setVolume(.3); control.setVolume(.2);
  assert.equal(calls.length, 1, 'writes serialize and coalesce while a request is in flight');
  assert.deepEqual(calls[0].payload, { projectId: 'a', trackId: 'one', volume: .5 });
  calls.shift().resolve({ projectId: 'a', trackId: 'one', volume: .5 }); await tick();
  assert.equal(state.volume, .2); assert.equal(calls[0].payload.volume, .2);
  control.updateProject('b');
  assert.equal(state, null);
  calls.shift().resolve({ projectId: 'a', trackId: 'one', volume: .2 }); await tick();
  assert.equal(state, null, 'a late write cannot populate the new project');
  read = control.refresh(); calls.shift().resolve({ projectId: 'b', trackId: 'two', volume: .8 }); await read;
  read = control.refresh();
  const staleRead = calls.shift();
  control.setVolume(.4);
  staleRead.resolve({ projectId: 'b', trackId: 'two', volume: .8 }); await read;
  assert.equal(state.volume, .4, 'a stale fader poll cannot undo a slider gesture');
  calls.shift().resolve({ projectId: 'b', trackId: 'two', volume: .4 }); await tick();
  control.setVolume(NaN); control.setVolume(-1); control.setVolume(9);
  assert.equal(calls.length, 0);
  read = control.refresh(); calls.shift().resolve({ projectId: 'b' }); await read;
  assert.equal(state, null); control.setVolume(.2); assert.equal(calls.length, 0);
  read = control.refresh(); control.updateProject('c');
  calls.shift().resolve({ projectId: 'b', trackId: 'two', volume: .4 }); await read;
  assert.equal(state, null, 'a stale read cannot expose the old project fader');
  read = control.refresh(); calls.shift().resolve({ projectId: 'c', trackId: 'three', volume: 1, solo: false }); await read;
  control.setVolume(.5);
  control.setSolo(true); control.setSolo(false); control.setSolo(true);
  control.setVolume(.4);
  assert.equal(calls.length, 1, 'solo and volume share the same write queue');
  calls.shift().resolve({ projectId: 'c', trackId: 'three', volume: .5, solo: false }); await tick();
  assert.deepEqual(calls[0].payload, { projectId: 'c', trackId: 'three', solo: true }, 'coalesce solo changes without losing queued volume');
  calls.shift().resolve({ projectId: 'c', trackId: 'three', volume: .5, solo: true }); await tick();
  assert.equal(calls[0].payload.volume, .4);
  calls.shift().resolve({ projectId: 'c', trackId: 'three', volume: .4, solo: true }); await tick();
  assert.equal(state.solo, true); assert.equal(state.volume, .4);
  control.setSolo('true'); control.setSolo(1); assert.equal(calls.length, 0);
  control.setSolo(false);
  assert.equal(calls[0].payload.solo, false, 'off is an explicit boolean write');
  control.updateProject('d');
  calls.shift().resolve({ projectId: 'c', trackId: 'three', volume: .4, solo: false }); await tick();
  assert.equal(state, null, 'late solo replies cannot affect the next project');
  control.setSolo(true); assert.equal(calls.length, 0, 'missing track cannot be soloed');
  assert.deepEqual(errors, []);
  console.log('Bridge track controls passed: volume/solo coalescing, stale reads/writes, project changes, missing tracks and invalid values.');
})().catch(error => { console.error(error); process.exitCode = 1; });
